    private fun e(code: String, sido: String, vararg names: String): Entry =
        Entry(code, sido, names.map { it.lowercase() })

    /**
     * 위치 문자열 → 시군구 5자리 코드. 시도를 먼저 식별해 동일명을 구분하고, 가장 구체적인(긴) 토큰으로 매칭.
     * 미매칭 시 null(→ RTMS comps 생략, 매크로·임대시장 실측은 그대로).
     */
    fun resolve(location: String?): String? {
        if (location.isNullOrBlank()) return null
        val s = location.lowercase().replace("\\s".toRegex(), "")
        val sido = SIDO_ALIASES.entries.firstOrNull { (_, aliases) -> aliases.any { s.contains(it) } }?.key
        val pool = if (sido != null) ENTRIES.filter { it.sido == sido } else ENTRIES

        var best: Entry? = null
        var bestLen = 0
        for (entry in pool) {
            for (name in entry.names) {
                if (name.length > bestLen && s.contains(name)) {
                    best = entry
                    bestLen = name.length
                }
            }
        }
        return best?.code
    }
