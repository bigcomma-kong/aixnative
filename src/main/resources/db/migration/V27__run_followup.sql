-- 분석 결과 후속 논의(질문하기·AI 검토 포인트 제안·반박 검토) 스레드. 테넌트 스코프.
-- 원본 분석(ai_tool_run)은 건드리지 않고 이 테이블에만 쌓는다. PostgreSQL / H2 공통 구문만(DB-agnostic).
CREATE TABLE ai_run_followup (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT      NOT NULL,   -- 테넌트(격리)
    owner_user_id BIGINT      NOT NULL,   -- 소유 사용자
    run_id        BIGINT      NOT NULL,   -- 대상 분석(ai_tool_run.id)
    deal_id       BIGINT,                 -- 대상 분석의 딜(참고 산출물 조립용 스냅샷)
    turn_seq      INT         NOT NULL,   -- 스레드 내 순서(0부터)
    role          VARCHAR(20) NOT NULL,   -- USER / AI / SUGGEST / CRITIQUE
    content       TEXT        NOT NULL,   -- 마크다운 본문(CRITIQUE 는 판정 JSON)
    provider      VARCHAR(40),            -- 생성 AI(USER 턴은 null)
    created_at    TIMESTAMP   NOT NULL
);

CREATE INDEX ix_ai_run_followup_run ON ai_run_followup (tenant_id, owner_user_id, run_id, turn_seq);
